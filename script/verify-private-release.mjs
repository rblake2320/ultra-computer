import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import {fileURLToPath} from 'node:url';
import { root } from "./private-runtime.mjs";

export function verifyReleasePayload(required = false) {
  const filename = path.join(root, "release-manifest.json");
  if (!fs.existsSync(filename)) {
    if (required) throw new Error('No release manifest exists. Install or package a release before checking artifact integrity.');
    return; // Git installations have their own source history.
  }
  const manifest = JSON.parse(fs.readFileSync(filename, "utf8"));
  if (manifest.version !== 1 || !/^[a-f0-9]{40}$/.test(manifest.sourceCommit) || !Array.isArray(manifest.files) || !manifest.files.length) throw new Error("Invalid release manifest");
  const paths = new Set();
  for (const file of manifest.files) {
    if (typeof file.path !== "string" || path.isAbsolute(file.path) || file.path.split(/[\\/]/).includes("..") || paths.has(file.path)) throw new Error("Invalid release manifest path");
    paths.add(file.path);
    // Built files are regenerated by setup on the owner's OS. Source and SBOM
    // stay immutable; verify the full artifact via GitHub before extraction.
    if (file.path.startsWith("dist/")) continue;
    const source = path.join(root, file.path);
    const physicalRoot = fs.realpathSync(root);
    if (fs.existsSync(source)) { const physical = fs.realpathSync(source); const relative = path.relative(physicalRoot, physical); if (relative.startsWith("..") || path.isAbsolute(relative)) throw new Error("Release file escapes its root"); }
    if (!fs.existsSync(source) || !fs.lstatSync(source).isFile() || fs.lstatSync(source).isSymbolicLink() || createHash("sha256").update(fs.readFileSync(source)).digest("hex") !== file.sha256) throw new Error(`Release source integrity failed: ${file.path}`);
  }
  console.log(`Worked: release source and SBOM match ${manifest.sourceCommit}.`);
}
if (process.argv[1] && fs.existsSync(process.argv[1]) && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  try { verifyReleasePayload(true); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
